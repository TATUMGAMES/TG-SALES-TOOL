"""Create a new PostgreSQL migration from the difference between the models and the schema.

Starts a throwaway PostgreSQL server, upgrades an empty database to the
current head, and lets Alembic autogenerate a revision for whatever
``db/models.py`` adds or changes. Review and edit the generated file (data
migrations, triggers and seed data are never autogenerated).

    .venv\\Scripts\\python scripts\\new_migration.py "add widget table" 0002
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from alembic import command  # noqa: E402
from tests.pg import start_test_server  # noqa: E402

from tg_sales.db.database import alembic_config  # noqa: E402
from tg_sales.db.engine import create_pg_engine  # noqa: E402


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write('usage: new_migration.py "message" <revision id, e.g. 0002>\n')
        return 2
    message, revision = sys.argv[1], sys.argv[2]
    with tempfile.TemporaryDirectory() as scratch:
        server = start_test_server(Path(scratch))
        if server is None:
            sys.stderr.write("PostgreSQL runtime not found; run scripts/setup_postgres.py.\n")
            return 1
        try:
            engine = create_pg_engine(server.create_database(), pool_size=1)
            config = alembic_config()
            with engine.begin() as connection:
                config.attributes["connection"] = connection
                command.revision(config, message=message, autogenerate=True, rev_id=revision)
            engine.dispose()
        finally:
            server.stop()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
