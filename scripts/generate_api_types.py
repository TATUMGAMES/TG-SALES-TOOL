"""Generate web/src/lib/api-types.ts and docs/API.md from the API's OpenAPI schema.

Keeps the web app's types and the endpoint reference identical to what the
server provides. Run after changing API routes or models:

    .venv/Scripts/python scripts/generate_api_types.py          # write
    .venv/Scripts/python scripts/generate_api_types.py --check  # fail if out of date (CI)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tg_sales.api.app import create_app  # noqa: E402
from tg_sales.api.settings import Environment, ServerSettings  # noqa: E402

TARGET = ROOT / "web" / "src" / "lib" / "api-types.ts"
API_DOC = ROOT / "docs" / "API.md"
API_DOC_HEADER = """# TG Sales CRM HTTP API

Generated by `scripts/generate_api_types.py` from the server's OpenAPI schema; do
not edit by hand. The web app and any future mobile app use this API.

- Base path: `/api`. JSON in and out, UTF-8, timestamps in UTC (ISO 8601).
- Every request that changes data must send the header `X-TG-Sales: 1`
  (protection against cross-site request forgery). Requests are accepted only
  for the host names `127.0.0.1` and `localhost`.
- Errors: `{"error": {"message", "action", "code"}}` with HTTP 400 (refused),
  403 (forbidden), 404 (not found), 409 (conflict, e.g. edited elsewhere) or
  422 (invalid input; a `problems` list names the fields).
- Slow work (imports, discovery, reports, backups, restore, sync) returns
  `{"job_id"}`; poll `GET /api/jobs/{job_id}` for `status`, `percent`,
  `message` and finally `result` or `error`; cancel with
  `POST /api/jobs/{job_id}/cancel`.
- Interactive documentation (Swagger UI) is available at `/api/docs` when the
  server runs with `TG_SALES_ENVIRONMENT=development`.
- There is no sign-in yet: the server only accepts connections from this
  computer (see DEPLOYMENT.md).

"""
HEADER = "// Generated by scripts/generate_api_types.py from the API schema. Do not edit.\n\n"


def type_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return cleaned[0].upper() + cleaned[1:]


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = sorted({ts(s) for s in schema[key]}, key=lambda p: (p == "null", p))
            return " | ".join(parts)
    if "allOf" in schema:
        return " & ".join(ts(s) for s in schema["allOf"])
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "const" in schema:
        return f'"{schema["const"]}"'
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**schema, "type": k}) for k in kind)
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s) for s in schema["prefixItems"]) + "]"
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        if "properties" in schema:
            return inline_object(schema)
        extra = schema.get("additionalProperties")
        value = ts(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def inline_object(schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    fields = []
    for name, prop in schema.get("properties", {}).items():
        optional = "" if name in required else "?"
        fields.append(f"{name}{optional}: {ts(prop)}")
    return "{ " + "; ".join(fields) + " }"


def generate() -> str:
    server = ServerSettings(environment=Environment.DEVELOPMENT)
    app = create_app(SimpleNamespace(server=server))  # type: ignore[arg-type]
    schemas = app.openapi()["components"]["schemas"]
    out = [HEADER]
    for name in sorted(schemas):
        schema = schemas[name]
        tname = type_name(name)
        if "enum" in schema:
            out.append(f"export type {tname} = {ts(schema)};\n\n")
            continue
        if schema.get("type") == "object" or "properties" in schema:
            required = set(schema.get("required", []))
            lines = [f"export interface {tname} {{"]
            for prop_name, prop in schema.get("properties", {}).items():
                optional = "" if prop_name in required else "?"
                lines.append(f"  {prop_name}{optional}: {ts(prop)};")
            lines.append("}\n\n")
            out.append("\n".join(lines))
        else:
            out.append(f"export type {tname} = {ts(schema)};\n\n")
    return "".join(out).rstrip() + "\n"


def api_markdown() -> str:
    server = ServerSettings(environment=Environment.DEVELOPMENT)
    app = create_app(SimpleNamespace(server=server))  # type: ignore[arg-type]
    paths = app.openapi()["paths"]
    by_tag: dict[str, list[tuple[str, str, str]]] = {}
    for path, operations in sorted(paths.items()):
        for method, operation in operations.items():
            tag = (operation.get("tags") or ["other"])[0]
            summary = operation.get("summary") or ""
            description = (operation.get("description") or "").strip().splitlines()
            text = description[0] if description else summary
            by_tag.setdefault(tag, []).append((method.upper(), path, text))
    out = [API_DOC_HEADER]
    for tag in sorted(by_tag):
        out.append(f"## {tag.capitalize()}\n\n| Method | Path | Purpose |\n|---|---|---|\n")
        for method, path, text in by_tag[tag]:
            out.append(f"| `{method}` | `{path}` | {text} |\n")
        out.append("\n")
    return "".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {TARGET: generate(), API_DOC: api_markdown()}
    if args.check:
        stale = [
            path.relative_to(ROOT).as_posix()
            for path, content in outputs.items()
            if (path.read_text(encoding="utf-8") if path.exists() else "") != content
        ]
        if stale:
            sys.stderr.write(f"Out of date: {', '.join(stale)}. Run the generator.\n")
            return 1
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
